        private void GenerateEnglishFrom(Language source)
        {
            var en = new Language { Code = "en", DisplayName = "English" };
            // For each source entry, keep the key but use the key itself as value
            // (so at least the UI shows something readable).
            foreach (var kv in source.Map)
                en.Map[kv.Key] = kv.Key; // key-as-value fallback
            _languages["en"] = en;
            _english = en;

            // Write it to disk so user can edit later.
            var lines = new List<string> { "# Auto-generated English fallback (edit freely)", $"__LANG_NAME__:English", "" };
            foreach (var kv in en.Map)
                lines.Add($"{kv.Key}:{kv.Value}");
            // Sort keys for deterministic output.
            lines.Sort();
            File.WriteAllLines(Path.Combine(LangDir, "en.txt"), lines, new UTF8Encoding(false));
        }

        private string DetectSystemLocale()
        {
            // Try to match system language to our available codes.
            try
            {
                string sysLang = UnityEngine.Application.systemLanguage.ToString();
                if (sysLang != null)
                {
                    string sl = sysLang.ToLowerInvariant();
                    if (sl.Contains("chinese") || sl.Contains("zh")) return "zh-cn";
                    if (sl.Contains("japanese") || sl.Contains("jp")) return "jp";
                    if (sl.Contains("english") || sl.Contains("en")) return "en";
                }
            }
            catch { /* ignore */ }
            return "en";
        }
