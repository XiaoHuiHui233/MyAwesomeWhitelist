    /// <summary>
    /// A loaded language: its code (from filename), display name (from __LANG_NAME__),
    /// and key→value map.
    /// </summary>
    internal sealed class Language
    {
        public string Code;          // e.g. "zh-cn", "en", "jp"
        public string DisplayName;   // e.g. "简体中文", "English", "日本語"
        public readonly Dictionary<string, string> Map = new Dictionary<string, string>();
    }

    /// <summary>
    /// Localization manager. Scans the lang/ directory for *.txt files, builds per-language
    /// maps, and resolves keys with fallback: current → English → key itself.
    /// Switching languages takes effect immediately.
    ///
    /// Language file format (one per line):
    ///   <code>KEY:Translation</code>
    ///   Lines starting with '#' are comments. Blank lines ignored.
    ///   Special key <c>__LANG_NAME__</c> sets the display name for the picker.
    ///   Escape '\n' in values becomes newline.
    /// </summary>
    internal sealed class LocalizationService
    {
        private static LocalizationService _instance;
        private readonly Dictionary<string, Language> _languages = new Dictionary<string, Language>();
        private Language _current;
        private Language _english;

        public static LocalizationService Instance { get { return _instance; } }

        /// <summary>All loaded languages, English first then others.</summary>
        public IEnumerable<Language> Languages
        {
            get
            {
                if (_english != null) yield return _english;
                foreach (var kvp in _languages)
                    if (kvp.Value != _english) yield return kvp.Value;
            }
        }

        /// <summary>Current language code (e.g. "zh-cn").</summary>
        public string CurrentCode => _current != null ? _current.Code : "en";

        public static void Init()
        {
            _instance = new LocalizationService();
            _instance.Reload();
        }

        /// <summary>(Re)scan lang/ directory and build all maps.</summary>
        public void Reload()
        {
            _languages.Clear();
            _english = null;
            _current = null;

            // Always generate default files on first run (idempotent — won't overwrite user edits).
            EnsureDefaultFiles();

            string langDir = LangDir;
            if (!Directory.Exists(langDir))
                return;

            foreach (var path in Directory.GetFiles(langDir, "*.txt"))
            {
                string code = Path.GetFileNameWithoutExtension(path);
                string displayName;
                var entries = LangFile.Parse(path, out displayName);

                var lang = new Language { Code = code };
                foreach (var e in entries)
                    lang.Map[e.Key] = e.Value;
                lang.DisplayName = displayName ?? code;

                // Top up keys this plugin version knows about but the file
                // (generated by an older version) is missing — both in memory
                // and on disk, so the value never falls back to the raw key.
                TopUpMissingKeys(path, code, lang);

                _languages[code] = lang;
                if (code == "en") _english = lang;
            }

            // If no en.txt exists yet, generate it from zh-cn as base.
            if (_english == null && _languages.ContainsKey("zh-cn"))
            {
                GenerateEnglishFrom(_languages["zh-cn"]);
            }

            // Auto-detect on first launch: use saved preference > system locale > "en".
            string preferred = Plugin.Config.LanguageCode.Value;
            string detected = DetectSystemLocale();
            string target = _languages.ContainsKey(preferred) ? preferred
                         : (_languages.ContainsKey(detected) ? detected : "en");
            SetLanguage(target);

            Plugin.Logger.LogInfo($"[I18n] Loaded {_languages.Count} language(s): {string.Join(", ", _languages.Keys)} · active: {CurrentCode}");
        }

        /// <summary>Set current language by code. Returns false if not found.</summary>
        public bool SetLanguage(string code)
        {
            if (code == null || !_languages.ContainsKey(code))
                return false;
            _current = _languages[code];
            return true;
        }

        /// <summary>Resolve a key: current → English → key itself.</summary>
        public string Get(string key)
        {
            if (string.IsNullOrEmpty(key)) return string.Empty;

            // 1) Current language
            if (_current != null)
            {
                string v;
                if (_current.Map.TryGetValue(key, out v) && !string.IsNullOrEmpty(v))
                    return v;
            }
            // 2) English fallback
            if (_english != null && _current != _english)
            {
                string v;
                if (_english.Map.TryGetValue(key, out v) && !string.IsNullOrEmpty(v))
                    return v;
            }
            // 3) Key itself as last resort
            return key;
        }

        /// <summary>Display name for a language picker.</summary>
        public string DisplayNameOf(string code)
        {
            Language lang;
            return _languages.TryGetValue(code, out lang) ? (lang.DisplayName ?? code) : code;
        }

        /// <summary>Available language codes for a dropdown/picker.</summary>
        public string[] AvailableCodes
        {
            get
            {
                var list = new List<string>(_languages.Keys);
                list.Sort();
                return list.ToArray();
            }
        }

        // ── File management ───────────────────────────────────────────

        private static string LangDir => Path.Combine(Paths.ConfigPath, PluginInfo.PLUGIN_NAME, "lang");

        /// <summary>Built-in defaults per language code ("key:value" lines).</summary>
        private static Dictionary<string, string[]> DefaultLines()
        {
            // Reflection-free: the writer methods below own the line arrays,
            // but they are also needed here for top-up, so duplicate the call.
            return new Dictionary<string, string[]>
            {
                { "zh-cn", ZhCnLines() },
                { "en", EnLines() },
                { "jp", JpLines() },
            };
        }

        /// <summary>Append any keys present in the built-in defaults but
        /// missing from the user's (possibly older) file, then add them to
        /// the in-memory map. Never touches keys the user already has.</summary>
        private static void TopUpMissingKeys(string path, string code, Language lang)
        {
            Dictionary<string, string[]> defaults;
            try { defaults = DefaultLines(); }
            catch { return; }
            string[] lines;
            if (!defaults.TryGetValue(code, out lines)) return;

            var missing = new List<string>();
            for (int i = 0; i < lines.Length; i++)
            {
                string line = lines[i];
                int colon = line.IndexOf(':');
                if (colon <= 0) continue; // comment / blank
                string key = line.Substring(0, colon);
                if (key == "__LANG_NAME__" || lang.Map.ContainsKey(key)) continue;
                lang.Map[key] = line.Substring(colon + 1);
                missing.Add(line);
            }
            if (missing.Count == 0) return;
            try
            {
                File.AppendAllText(path,
                    Environment.NewLine + "# --- added by upgrade (v" + PluginInfo.PLUGIN_VERSION + ") ---" + Environment.NewLine
                    + string.Join(Environment.NewLine, missing.ToArray()) + Environment.NewLine,
                    new UTF8Encoding(false));
                Plugin.Logger.LogInfo($"[I18n] Added {missing.Count} new key(s) to {Path.GetFileName(path)}");
            }
            catch (Exception e)
            {
                Plugin.Logger.LogWarning($"[I18n] Could not append new keys to {Path.GetFileName(path)}: {e.Message}");
            }
        }

        private void EnsureDefaultFiles()
        {
            Directory.CreateDirectory(LangDir);

            // Only create defaults if the directory is empty or missing target files.
            if (!File.Exists(Path.Combine(LangDir, "zh-cn.txt")))
                WriteDefaultZhCn();
            if (!File.Exists(Path.Combine(LangDir, "en.txt")))
                WriteDefaultEn();
            if (!File.Exists(Path.Combine(LangDir, "jp.txt")))
                WriteDefaultJp();
        }

